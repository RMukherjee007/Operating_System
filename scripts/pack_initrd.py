#!/usr/bin/env python3
"""
Pack compiled EL0 ELF binaries and C/C++ source files into build/initrd_data.c
so FulmenOS mounts them directly into its hierarchical RAM disk at boot.
"""

import argparse
import os
import sys


def c_escape_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate C initrd payload for FulmenOS.")
    parser.add_argument("--out", required=True, help="Output C file path")
    parser.add_argument(
        "--entry",
        action="append",
        default=[],
        help="Mapping in the form /vfs/path=local/file/path",
    )
    args = parser.parse_args()

    entries = []
    for spec in args.entry:
        if "=" not in spec:
            print(f"Invalid --entry spec: {spec}", file=sys.stderr)
            return 1
        vfs_path, local_path = spec.split("=", 1)
        if not os.path.isfile(local_path):
            print(f"Missing initrd input file: {local_path}", file=sys.stderr)
            return 1
        with open(local_path, "rb") as f:
            data = f.read()
        entries.append((vfs_path, data))

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as out:
        out.write("/* Auto-generated by scripts/pack_initrd.py — do not edit */\n")
        out.write('#include "types.h"\n\n')
        out.write("struct initrd_entry {\n")
        out.write("    const char *path;\n")
        out.write("    const uint8_t *data;\n")
        out.write("    size_t size;\n")
        out.write("};\n\n")

        for idx, (vfs_path, data) in enumerate(entries):
            out.write(f"/* {vfs_path} ({len(data)} bytes) */\n")
            out.write(f"static const uint8_t initrd_blob_{idx}[] = {{\n")
            if len(data) == 0:
                out.write("    0x00\n")
            else:
                for off in range(0, len(data), 16):
                    chunk = data[off : off + 16]
                    hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
                    out.write(f"    {hex_bytes},\n")
            out.write("};\n\n")

        out.write("const struct initrd_entry g_initrd_entries[] = {\n")
        for idx, (vfs_path, data) in enumerate(entries):
            out.write(
                f'    {{ "{c_escape_string(vfs_path)}", initrd_blob_{idx}, {len(data)} }},\n'
            )
        out.write("};\n\n")
        out.write(
            f"const size_t g_initrd_entry_count = {len(entries)};\n"
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
